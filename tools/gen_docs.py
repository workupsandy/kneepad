#!/usr/bin/env python3
"""Generate docs/FOOTGUNS.md from the rule database. Run: python3 tools/gen_docs.py"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
from kneepad.rules import load_default_rules  # noqa: E402

rules = load_default_rules()
fams = {}
for r in rules:
    fams.setdefault(r.family, []).append(r)
real = [r for r in rules if not r.virtual]
tools = set()
import re  # noqa: E402
for r in real:
    for t in r.match.get("cmd", []):
        tools.add(t)
    cr = r.match.get("cmd_re")
    if cr:
        for alt in re.sub(r"^\(\?:|\)$", "", cr).split("|"):
            alt = alt.strip("()")
            if re.fullmatch(r"[A-Za-z0-9_.\-]+", alt):
                tools.add(alt)
n_ex = sum(len(r.examples.get("match", [])) for r in real)
n_no = sum(len(r.examples.get("no_match", [])) for r in real)
out = [
    "# Footgun database",
    "",
    "Generated by `tools/gen_docs.py` from `src/kneepad/data/footguns*.toml`. Do not edit by hand.",
    "",
    f"- {len(rules)} rules: {len(real)} pattern rules plus {len(rules) - len(real)} emitted by engine code (rm, find, git, pipe-to-shell, SQL, protected paths).",
    f"- Pattern rules name about {len(tools)} distinct tools. Each rule is a pattern family, so one rule covers many concrete commands (every `delete`/`destroy`/`terminate` subcommand of a CLI, for example).",
    f"- {n_ex} executable `match` examples and {n_no} `no_match` examples run in the test suite. This page cannot drift from behaviour.",
    "",
    "This is a count of rules and verified examples. It is not a count of \"commands covered\", and a higher number is not automatically a better safety net: every rule is a chance of a false positive.",
    "",
]
for fam in sorted(fams):
    out += [f"## {fam}", "", "| id | severity | action | what it stops |", "|---|---|---|---|"]
    for r in sorted(fams[fam], key=lambda x: x.id):
        out.append(f"| `{r.id}` | {r.severity} | {r.action} | {r.title.replace('|', '/')} |")
    out.append("")
path = os.path.join(ROOT, "docs", "FOOTGUNS.md")
open(path, "w", encoding="utf-8").write("\n".join(out))
print(f"wrote {path}: {len(rules)} rules, {len(real)} pattern, ~{len(tools)} tools, {n_ex}+{n_no} examples")
